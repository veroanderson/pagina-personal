-- Explicit grants keep the migration independent from project-level default
-- privileges. RLS remains the authorization boundary.
grant select on public.manifesto, public.bio, public.series, public.artworks
  to anon, authenticated;
grant select, insert, update, delete on
  public.manifesto,
  public.bio,
  public.series,
  public.artworks,
  public.settings,
  public.contact_requests,
  public.admin_users
  to authenticated;
grant usage, select on all sequences in schema public to authenticated;

create policy "published manifesto is readable"
  on public.manifesto for select
  to anon, authenticated
  using (true);

create policy "published bio is readable"
  on public.bio for select
  to anon, authenticated
  using (true);

create policy "published series are readable"
  on public.series for select
  to anon, authenticated
  using (deleted_at is null and is_active = true);

create policy "published artworks are readable"
  on public.artworks for select
  to anon, authenticated
  using (
    deleted_at is null
    and exists (
      select 1
      from public.series
      where public.series.id = public.artworks.series_id
        and public.series.deleted_at is null
        and public.series.is_active = true
    )
  );

