-- Storage is configured here so the application and its permissions are
-- reproducible. Files are uploaded to this public bucket only after browser
-- compression in the later Storage phase.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values (
  'portfolio-images',
  'portfolio-images',
  true,
  5242880,
  array['image/jpeg', 'image/png', 'image/webp']::text[]
)
on conflict (id) do update set
  public = excluded.public,
  file_size_limit = excluded.file_size_limit,
  allowed_mime_types = excluded.allowed_mime_types;

create policy "portfolio images are publicly readable"
  on storage.objects for select
  to anon, authenticated
  using (bucket_id = 'portfolio-images');

create policy "admins upload portfolio images"
  on storage.objects for insert
  to authenticated
  with check (
    bucket_id = 'portfolio-images'
    and public.is_admin()
  );

create policy "admins update portfolio images"
  on storage.objects for update
  to authenticated
  using (
    bucket_id = 'portfolio-images'
    and public.is_admin()
  )
  with check (
    bucket_id = 'portfolio-images'
    and public.is_admin()
  );

create policy "admins delete portfolio images"
  on storage.objects for delete
  to authenticated
  using (
    bucket_id = 'portfolio-images'
    and public.is_admin()
  );